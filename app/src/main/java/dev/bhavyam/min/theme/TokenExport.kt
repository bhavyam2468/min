package dev.bhavyam.min.theme

import org.json.JSONObject
import java.util.Locale

/** Token Studio's exporters: the current look as a `globals.css` or a W3C DTCG `tokens.json`. */
object TokenExport {

    fun css(theme: Theme): String = buildString {
        append("/* globals.css — generated by min · Token Studio */\n:root {\n")
        for ((name, value) in variables(theme)) append("  ").append(name).append(": ").append(value).append(";\n")
        append("}\n")
    }

    fun json(theme: Theme): String {
        val t = theme.tokens
        val vars = variables(theme).toMap()
        fun token(type: String, value: Any) = JSONObject().put("\$type", type).put("\$value", value)
        val color = JSONObject()
        for ((name, value) in vars) if (name.startsWith("--c-")) color.put(name.removePrefix("--c-"), token("color", value))
        val button = JSONObject()
        TIERS.forEachIndexed { i, tier -> button.put(tier, token("string", theme.variant(i).label.lowercase(Locale.ROOT))) }
        return JSONObject()
            .put("\$description", "Design tokens (W3C DTCG format) — generated by min · Token Studio")
            .put("color", color)
            .put("radius", JSONObject()
                .put("card", token("dimension", vars.getValue("--radius-card")))
                .put("button", token("dimension", vars.getValue("--radius-btn")))
                .put("small", token("dimension", vars.getValue("--radius-sm"))))
            .put("space", JSONObject()
                .put("button-x", token("dimension", vars.getValue("--pad-x")))
                .put("button-y", token("dimension", vars.getValue("--pad-y"))))
            .put("typography", JSONObject()
                .put("family", token("fontFamily", Fonts.ALL[t.font].name))
                .put("weight", token("fontWeight", t.weight.toInt()))
                .put("base", token("dimension", "${num(t.scale)}px")))
            .put("shadow", JSONObject().put("card", token("shadow", vars.getValue("--shadow-card"))))
            .put("icon", JSONObject()
                .put("style", token("string", theme.iconStyle.label.lowercase(Locale.ROOT)))
                .put("stroke", token("number", t.iconStroke.toDouble())))
            .put("button", button)
            .put("\$raw", t.toJson())
            .toString(2)
    }

    /** The same variable set Token Studio writes, from the derived theme. */
    private fun variables(theme: Theme): List<Pair<String, String>> {
        val t = theme.tokens
        val e = t.elevation
        val vars = mutableListOf(
            "--c-bg" to hex(theme.bg),
            "--c-surface" to hex(theme.surface),
            "--c-surface-2" to hex(theme.surface2),
            "--c-border" to hex(theme.border),
            "--c-text" to hex(theme.text),
            "--c-muted" to hex(theme.muted),
        )
        ROLES.forEachIndexed { i, name ->
            val r = theme.roles[i]
            vars += "--c-$name" to hex(r.color)
            vars += "--c-on-$name" to hex(r.on)
            vars += "--c-$name-soft" to hex(r.soft)
            vars += "--c-$name-ink" to hex(r.ink)
            vars += "--g-$name" to "linear-gradient(135deg, ${hex(r.gradientStart)}, ${hex(r.gradientEnd)})"
        }
        // Shadows are tinted by the neutral hue in light themes, near-black in dark ones.
        fun sh(alpha: Float) = rgba(
            if (t.isDark) Oklch.toArgb(0.04f, 0f, 0f, alpha) else Oklch.toArgb(0.25f, t.neutralChroma + 0.02f, t.neutralHue, alpha),
        )
        vars += "--shadow-card" to "0 ${num(0.04f + e * 0.08f)}em ${num(0.1f + e * 0.2f)}em ${sh(0.04f + e * 0.06f)}, " +
            "0 ${num(e * 1.3f)}em ${num(e * 3.2f)}em -${num(e * 0.9f)}em ${sh(e * if (t.isDark) 0.7f else 0.3f)}"
        vars += "--shadow-btn" to "0 ${num(e * 0.12f)}em ${num(e * 0.3f)}em ${sh(e * 0.18f)}, " +
            "0 ${num(e * 0.45f)}em ${num(e)}em -${num(e * 0.3f)}em ${sh(e * 0.35f)}, " +
            "inset 0 1px 0 rgb(255 255 255 / ${num(e * 0.22f)})"
        vars += "--lift" to num(e)
        vars += "--radius-card" to "${num(t.radiusCard)}em"
        vars += "--radius-btn" to "${num(t.radiusBtn)}em"
        vars += "--radius-sm" to "${num(t.radiusBtn * SMALL_RADIUS)}em"
        vars += "--pad-x" to "${num(t.padX)}em"
        vars += "--pad-y" to "${num(t.padY)}em"
        vars += "--density" to num(theme.density)
        vars += "--font" to Fonts.ALL[t.font].cssStack
        vars += "--weight" to t.weight.toInt().toString()
        vars += "--weight-strong" to (t.weight.toInt() + Theme.STRONG_OFFSET).coerceIn(Theme.STRONG_MIN, Theme.STRONG_MAX).toString()
        vars += "--scale" to "${num(t.scale)}px"
        vars += "--ico-fill-op" to num(theme.iconStyle.fillAlpha)
        vars += "--ico-cap" to theme.iconStyle.cap.name.lowercase(Locale.ROOT)
        vars += "--ico-join" to theme.iconStyle.join.name.lowercase(Locale.ROOT)
        vars += "--ico-stroke" to num(t.iconStroke)
        return vars
    }

    private fun hex(c: Int) = String.format(Locale.ROOT, "#%06x", c and 0xFFFFFF)

    private fun rgba(c: Int) = String.format(
        Locale.ROOT, "rgb(%d %d %d / %s)", c shr 16 and 0xFF, c shr 8 and 0xFF, c and 0xFF, num((c ushr 24) / 255f),
    )

    /** Up to three decimals, trailing zeros dropped (Token Studio's `r3`). */
    private fun num(v: Float) = String.format(Locale.ROOT, "%.3f", v).trimEnd('0').trimEnd('.')

    private val ROLES = listOf("primary", "accent", "neutral")
    private val TIERS = listOf("primary", "secondary", "tertiary")
    private const val SMALL_RADIUS = 0.6f
}
